"""Real locations and drive times for the schools and landmarks shown on the home page and school maps.

Coordinates come from OpenStreetMap. Each drive is routed from the north entry on Bois D'Arc Lane with the public OSRM
demo server, so times and distances are estimates from road data. Writes js/place-geo.js.

Run from the project folder, after kit_geo.py:  python -I tools/kit_places.py
"""
import json
import time
import urllib.request
from pathlib import Path

PLACES = {  # number on the kit's area map: [longitude, latitude]
    1: [-95.8932083, 29.6986576],    # Huggins Elementary School, 1 Huggins Drive
    2: [-95.8866349, 29.6945215],    # James W. Roberts Middle School, Charger Way
    3: [-95.8858623, 29.7010412],    # Dean Leaman Junior High School, 9320 Charger Way
    4: [-95.8858117, 29.6975231],    # Fulshear High School, Charger Way
    5: [-95.6981067, 29.7872914],    # Houston Methodist West Hospital, 18500 Katy Freeway
    8: [-95.7747, 29.7419],          # LaCenterra at Cinco Ranch, 23501 Cinco Ranch Boulevard
    10: [-95.804049, 29.779401],     # Typhoon Texas, 555 Katy Fort Bend Road
    11: [-95.8484201, 29.7197961],   # H-E-B, 4950 FM 1463
    20: [-95.762012, 29.5803771],    # Fort Bend Museum, 500 Houston Street, Richmond
    21: [-95.6858484, 29.4966603],   # George Ranch Historical Park
    26: [-95.809401, 29.7755523],    # Katy Mills
    28: [-95.8888835, 29.6899798],   # Fulshear Farmers Market, 9035 Bois D'Arc Lane
}
text = Path('js/plan-geo.js').read_text(encoding='utf-8')
start = json.loads(text[text.index('{'):text.rindex('}') + 1])['entries'][0]
out = {'from': start, 'places': {}}
for n, ll in PLACES.items():
    url = f'https://router.project-osrm.org/route/v1/driving/{start[0]},{start[1]};{ll[0]},{ll[1]}?overview=full&geometries=geojson'
    req = urllib.request.Request(url, headers={'User-Agent': 'belmont-site-prototype/1.0'})
    r = json.loads(urllib.request.urlopen(req, timeout=40).read())['routes'][0]
    line = r['geometry']['coordinates'][::max(1, len(r['geometry']['coordinates']) // 90)] + [r['geometry']['coordinates'][-1]]
    out['places'][n] = {'ll': ll, 'min': max(1, round(r['duration'] / 60)), 'mi': round(r['distance'] / 1609.34, 1),
                        'route': [[round(a, 5), round(b, 5)] for a, b in line] if n <= 4 else []}
    print(n, out['places'][n]['min'], 'min', out['places'][n]['mi'], 'mi')
    time.sleep(1.1)
Path('js/place-geo.js').write_text('// Generated by tools/kit_places.py: real locations and estimated drives from the Bois D’Arc Lane entry.\nwindow.BE_PLACES = '
                                   + json.dumps(out, separators=(',', ':')) + ';\n', encoding='utf-8', newline='\n')
